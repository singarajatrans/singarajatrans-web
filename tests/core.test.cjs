const assert = require('node:assert/strict');
require('../assets/core.js');
const C=globalThis.Singaraja, now=new Date('2026-10-15T00:00:00Z');
const s={service:'shuttle',from:'Singaraja',to:'Denpasar',date:'2026-10-16',time:'',passengers:2};
assert.equal(C.getOptions(s,now).length,2);
assert.equal(C.getOptions(s,now)[0].total,240000);
assert.equal(C.getOptions({...s,time:'afternoon'},now)[0].time,'16:00');
assert.equal(C.getOptions({...s,time:'evening'},now).length,0);
assert.equal(C.getOptions({...s,from:'Denpasar',to:'Singaraja'},now).length,2);
assert.equal(C.getOptions({...s,to:s.from},now).length,0);
assert.equal(C.getOptions({...s,date:'2026-10-14'},now).length,0);
assert.equal(C.getOptions({...s,date:'2026-10-15'},new Date('2026-10-15T02:00:00Z')).length,1);
assert.equal(C.getOptions({...s,passengers:0},now).length,0);
assert.equal(C.getOptions({...s,passengers:1.5},now).length,0);
assert.equal(C.getOptions({...s,passengers:13},now).length,0);
assert.equal(C.getOptions({...s,service:'charter',time:'09:00'},now)[0].total,600000);
assert.equal(C.getOptions({...s,service:'airport',time:'09:00'},now).length,0);
const a={...s,service:'airport',from:'Bandara Ngurah Rai',to:'Singaraja',time:'09:00'};
assert.equal(C.getOptions(a,now).length,2);
assert.equal(C.getOptions({...a,passengers:7},now).length,1);
assert.equal(C.getOptions(a,now)[0].total,650000);
assert.equal(C.getOptions({...a,from:'Singaraja',to:'Bandara Ngurah Rai'},now)[0].price,650000);
assert.equal(C.baliDate(new Date('2026-10-15T17:00:00Z')),'2026-10-16');
assert.equal(new Set(C.routes.map(r=>r.from+'|'+r.to)).size,C.routes.length);
console.log('PASS: 19 reference fare, direction, capacity, date, and time assertions');
